import { t } from '../core/i18n.js';

const RESERVED_USERNAMES = new Set([
  'admin', 'milkyway', 'nova', 'support', 'official', 'moderator', 'system', 'orbit',
]);

export const USERNAME_COOLDOWN_MS = 72 * 60 * 60 * 1000;
const USERNAME_PATTERN = /^[a-z0-9_](?:[a-z0-9._]{1,18}[a-z0-9_])$/;

export function safePublicText(value) {
  if (typeof value !== 'string') return '';
  return value
    .replace(/[\w.+-]+@[\w.-]+\.[a-z]{2,}/gi, '')
    .replace(/\b(?:null|undefined)\b/gi, '')
    .replace(/\s+/g, ' ')
    .trim();
}

export function displayNameFromEmail(email) {
  const local = String(email || '').trim().split('@')[0] || '';
  const cleaned = local
    .replace(/([a-z])([A-Z])/g, '$1 $2')
    .replace(/[._-]+/g, ' ')
    .replace(/\d+$/g, '')
    .replace(/[^\p{L}\p{M}\s']/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  if (cleaned.replace(/[^\p{L}]/gu, '').length < 2) return t('defaultDisplayName');
  return cleaned.split(' ').map(word => {
    const lower = word.toLocaleLowerCase();
    return lower.replace(/^([\p{L}\p{M}])([\p{L}\p{M}'-]*)$/u, (_, first, rest) =>
      first.toLocaleUpperCase() + rest);
  }).join(' ');
}

function usernameBase(value) {
  return String(value || '')
    .normalize('NFKD').replace(/[\u0300-\u036f]/g, '')
    .toLowerCase().replace(/[^a-z0-9._]+/g, '.')
    .replace(/[._]{2,}/g, '.').replace(/^[._]+|[._]+$/g, '')
    .slice(0, 20).replace(/[.]+$/g, '');
}

export function validUsername(value) {
  return typeof value === 'string'
    && value.length >= 3 && value.length <= 20
    && USERNAME_PATTERN.test(value)
    && !RESERVED_USERNAMES.has(value);
}

export function usernameValidationMessage(value) {
  if (typeof value !== 'string' || value.length < 3 || value.length > 20
    || !/^[a-z0-9_](?:[a-z0-9._]{1,18}[a-z0-9_])$/.test(value)) return t('usernameRule');
  return RESERVED_USERNAMES.has(value) ? t('usernameReserved') : '';
}

export async function usernameAvailable(sb, username, excludeId = '') {
  const pattern = username.replace(/[\\%_]/g, '\\$&');
  const { data, error } = await sb.from('mw_profiles')
    .select('id').ilike('username', pattern).limit(20);
  if (error) throw error;
  return !(Array.isArray(data) ? data : []).some(row => String(row.id) !== String(excludeId));
}

export async function uniqueUsername(sb, source, { email = '', excludeId = '' } = {}) {
  let base = usernameBase(source) || usernameBase(String(email).split('@')[0]) || 'user';
  if (base.length < 3) base = `${base}user`.slice(0, 20);
  if (RESERVED_USERNAMES.has(base)) base = 'user';

  for (let suffix = 0; suffix < 1_000_000; suffix++) {
    const tail = suffix ? String(suffix) : '';
    const candidate = `${base.slice(0, 20 - tail.length)}${tail}`;
    if (validUsername(candidate) && await usernameAvailable(sb, candidate, excludeId)) return candidate;
  }
  throw new Error(t('usernameGenerationFailed'));
}

export async function registrationIdentity(sb, { email, requestedUsername = '', excludeId = '' }) {
  const displayName = displayNameFromEmail(email);
  const requested = String(requestedUsername || '').trim().replace(/^@/, '').toLowerCase();
  const customIsValid = validUsername(requested);
  if (customIsValid && await usernameAvailable(sb, requested, excludeId)) {
    return { displayName, username: requested, usernameAutoGenerated: false };
  }
  const source = displayName === t('defaultDisplayName') ? String(email).split('@')[0] : displayName;
  const username = await uniqueUsername(sb, source, { email, excludeId });
  return { displayName, username, usernameAutoGenerated: true };
}
